"""Prediction Presentation Models.

FastAPI response schemas compliant with Pydantic v2.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

class CurrentMarket(BaseModel):
    """Authoritative live pricing benchmarks."""
    lowest_fare: Optional[float] = Field(None, description="Lowest live fare observed.")
    average_fare: Optional[float] = Field(None, description="Average live fare observed.")
    snapshot_timestamp: str = Field(..., description="Timestamp of observed market snapshot.")
    provider: str = Field(..., description="Active market data provider name.")

class ForecastDay(BaseModel):
    """Daily forecast points."""
    day: int = Field(..., description="Day index from today.")
    date: str = Field(..., description="ISO calendar date.")
    price: float = Field(..., description="Predicted daily lowest price.")
    lower: float = Field(..., description="Lower confidence band bound.")
    upper: float = Field(..., description="Upper confidence band bound.")
    # Where the two bounds above came from. Null for a producer that does not
    # record it; when present it names the residual percentiles and the sample
    # they were measured on. The bounds used to be `price ± max(120, 6% of
    # price)` — a constant width with no relation to the model's error — and the
    # response said nothing that would let a reader notice.
    interval_basis: Optional[Dict[str, Any]] = Field(
        None, description="Provenance of the lower/upper bounds: the recorded "
                          "residual percentiles the width was derived from.")

    # Model V2 Future Forecast Engine alignment
    forecast_price: float = Field(..., description="Forecast price at this timeline point.")
    forecast_timestamp: str = Field(..., description="Timestamp forecast points targeted.")
    prediction_horizon: int = Field(..., description="Offset timeline prediction horizon in days.")
    # Optional, because null is a value this field is meant to carry. It was
    # `float` and required while `PredictionFormatter.format_forecast` publishes
    # None for a horizon whose model records no evaluation metrics — the state
    # that used to be filled with a fabricated 95.0. So the honest value could
    # not be serialized: a response FastAPI would have accepted with an invented
    # number failed validation with the truthful one, turning a published null
    # into a 500 at the response boundary.
    confidence: Optional[float] = Field(
        None, description="Confidence associated with this specific prediction; "
                          "null when this horizon's model records no evaluation.")
    model_version: str = Field(..., description="XGBoost model version used for this prediction.")
    feature_schema_version: str = Field(..., description="Feature schema version indicating columns sequence.")

class Recommendation(BaseModel):
    """Final booking advice generated by recommendation engine."""
    decision: str = Field(..., description="Recommended action: BOOK_NOW, WAIT, or MONITOR.")
    reasons: List[str] = Field(default_factory=list, description="Text reasons supporting decision.")
    confidence: Optional[float] = Field(None, description="Combined decision confidence (0.0 to 100.0).")

class SearchMetadata(BaseModel):
    """Metadata regarding live data searches."""
    provider: str = Field(..., description="Provider name query source.")
    retrieval_time: str = Field(..., description="Timestamp of when search resolved.")
    search_latency: Optional[float] = Field(None, description="Latency of provider query in seconds.")
    flight_count: int = Field(..., description="Total active flights parsed.")
    # The route and date the prediction is for. Absent from the response until
    # now, which left a client with two predictions unable to tell which was
    # which, and left the route-isolation test asserting a literal it supplied
    # itself.
    origin: Optional[str] = Field(None, description="Origin IATA code the prediction is for.")
    destination: Optional[str] = Field(None, description="Destination IATA code the prediction is for.")
    departure_date: Optional[str] = Field(None, description="Departure date the prediction is for (ISO).")
    market_freshness: Optional[float] = Field(None, description="Age of snapshot cache in seconds.")

    cache_hit: bool = Field(False, description="True if snapshot was served from cache.")
    cache_miss: bool = Field(False, description="True if snapshot required a new provider query.")
    refresh_reason: str = Field("TTL_EXPIRED", description="Reason for cache refresh: STARTUP, MANUAL_REFRESH, or TTL_EXPIRED.")
    snapshot_age: Optional[float] = Field(0.0, description="Calculated age of the returned snapshot in seconds.")
    prediction_mode: str = Field("live", description="Prediction mode: live or historical_only.")
    provider_status: str = Field("ONLINE", description="Status of market provider: ONLINE, DEGRADED, OFFLINE.")
    market_snapshot_available: bool = Field(True, description="True if live market snapshot was successfully fetched.")

class MarketSnapshotSummary(BaseModel):
    """High level summary of the current live market context."""
    total_live_flights: int
    average_fare: Optional[float] = None
    lowest_fare: Optional[float] = None
    highest_fare: Optional[float] = None
    connecting_flight_count: int
    direct_flight_count: int

class QuotedFlight(BaseModel):
    """The single flight a prediction is about.

    `current_market.lowest_fare` is the whole market's minimum, and the response
    carried nothing else, so a caller who named an airline could not tell which
    flight `predicted_price` referred to — and until this field existed neither
    could the service, which quoted the market minimum whatever carrier was asked
    for. `fare` is the number the forecast and the recommendation were computed
    from; it equals `lowest_fare` only when no airline was named.

    `flight_number` is null when the provider listed the flight without one. That
    is worth reading rather than ignoring: with no flight number there is no
    booking curve, so the model saw none of this flight's own price history.
    """
    airline: Optional[str] = Field(None, description="Carrier operating the quoted flight.")
    flight_number: Optional[str] = Field(None, description="Flight number of the quoted flight; null if the provider gave none.")
    fare: Optional[float] = Field(None, description="The quoted flight's current fare, which the forecast is computed from.")
    has_booking_curve: bool = Field(False, description="Whether the quoted flight is identified well enough to have a price history.")

class ConfidenceBreakdown(BaseModel):
    """Explicit confidence metrics breakdown."""
    model_validation_score: float = Field(..., description="Offline historical model evaluation accuracy percentage.")
    market_data_quality: float = Field(..., description="Upstream market snapshot data freshness & quality score (0.0 to 1.0).")
    prediction_reliability: float = Field(..., description="Effective inference reliability score (model_validation_score * market_data_quality).")

class PredictionResponse(BaseModel):
    """FastAPI return schema mapping predictions, current markets, and snapshot info."""
    schema_version: str = Field("1.0.0", description="Schema version of the API contract.")
    api_version: str = Field("v1", description="API endpoint version.")
    backend_version: str = Field("11.0.0", description="Backend release version.")
    prediction_version: str = Field("2.0.0", description="ML forecasting engine version.")
    
    predicted_price: float = Field(..., description="Authorized model price output.")
    current_market: CurrentMarket
    forecast: List[ForecastDay]
    recommendation: Recommendation
    confidence: float = Field(..., description="Inference confidence percentage.")
    confidence_breakdown: Optional[ConfidenceBreakdown] = Field(None, description="Disambiguated confidence metrics breakdown.")
    search_metadata: SearchMetadata
    market_snapshot: MarketSnapshotSummary
    quoted_flight: Optional[QuotedFlight] = Field(None, description="The flight this prediction is about.")
    prediction_horizon: int = Field(..., description="Timeline prediction horizon in days.")
